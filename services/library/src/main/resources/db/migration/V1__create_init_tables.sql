CREATE TABLE library.user_folder
(
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    created_at           TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    updated_at           TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    user_profile_id      UUID                        NOT NULL,
    name                 VARCHAR(255)                NOT NULL,
    cover_url            VARCHAR(255)                        ,
    position             INT                                 ,
    CONSTRAINT pk_user_folder PRIMARY KEY (id)
);

CREATE TABLE library.folder_item
(
    id                   BIGINT                      NOT NULL,
    created_at           TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    updated_at           TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    user_profile_id      UUID                        NOT NULL,
    media_item_id      UUID                        NOT NULL,
    deleted              BOOLEAN                     NOT NULL,
    CONSTRAINT pk_user_profile PRIMARY KEY (id)
);

ALTER TABLE library.user_folder
    ADD CONSTRAINT FK_USER_PROFILE_ON_FOLDER FOREIGN KEY (user_profile_id) REFERENCES library.user_profile_replica(id);

ALTER TABLE library.folder_item
    ADD CONSTRAINT FK_USER_PROFILE_ON_FOLDER_ITEM FOREIGN KEY (user_profile_id) REFERENCES library.user_profile_replica(id);

ALTER TABLE library.folder_item
    ADD CONSTRAINT FK_MEDIA_ITEM_ON_FOLDER_ITEM FOREIGN KEY (media_item_id) REFERENCES library.media_item_replica(id);
