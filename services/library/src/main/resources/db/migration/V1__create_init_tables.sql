CREATE TABLE library.user_folder
(
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    created_at           TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    updated_at           TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    user_profile_replica_id      UUID                NOT NULL,
    name                 VARCHAR(255)                NOT NULL,
    cover_url            VARCHAR(255)                        ,
    position             INT                                 ,
    CONSTRAINT pk_user_folder PRIMARY KEY (id)
);

CREATE TABLE library.folder_item
(
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    created_at           TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    updated_at           TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    media_item_replica_id        UUID                        ,
    media_group_replica_id       UUID                        ,
    user_folder_id       BIGINT                      NOT NULL,
    position             INT                                 ,
    CONSTRAINT pk_folder_item PRIMARY KEY (id),
    CONSTRAINT folder_item_mediaitem_or_mediagroup_not_null
        CHECK((media_item_replica_id IS NOT NULL) <> (media_group_replica_id IS NOT NULL)),
    CONSTRAINT folder_item_unique UNIQUE NULLS NOT DISTINCT (user_folder_id, media_item_replica_id, media_group_replica_id)

);

