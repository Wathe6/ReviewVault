CREATE TABLE review.rating (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    user_profile_replica_id UUID                NOT NULL,
    media_item_replica_id   UUID,
    media_group_replica_id  UUID,
    value            NUMERIC(5, 2)               NOT NULL,
    normalized_value INT                         NOT NULL,
    created_at       TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    updated_at       TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    CONSTRAINT pk_rating PRIMARY KEY (id),
    CONSTRAINT rating_mediaitem_or_mediagroup_not_null
    CHECK((media_item_replica_id IS NOT NULL) <> (media_group_replica_id IS NOT NULL)),
    CONSTRAINT rating_unique UNIQUE NULLS NOT DISTINCT (user_profile_replica_id, media_item_replica_id, media_group_replica_id)
);

CREATE TABLE review.rating_scale(
    id            SMALLINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    name          VARCHAR(12)   NOT NULL,
    min           NUMERIC(5, 2) NOT NULL,
    max           NUMERIC(5, 2) NOT NULL,
    step          NUMERIC(5, 2) NOT NULL,
    total_steps   INT           NOT NULL,
    type          VARCHAR(5)    NOT NULL ,
    created_at    TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    updated_at    TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    CONSTRAINT pk_rating_scale PRIMARY KEY (id)
);

CREATE TABLE review.user_rating_preference (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    user_profile_replica_id UUID NOT NULL,
    rating_scale_id  SMALLINT   NOT NULL,
    created_at    TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    updated_at    TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    CONSTRAINT pk_user_rating_preference PRIMARY KEY (id),
    CONSTRAINT unique_profile UNIQUE (user_profile_replica_id)
) ;

CREATE TABLE review.user_rating_description (
    id                      BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    user_profile_replica_id UUID NOT NULL,
    "left"                  NUMERIC(5, 2) NOT NULL,
    "right"                 NUMERIC(5, 2) NOT NULL,
    normalized_left         INT NOT NULL,
    normalized_right        INT NOT NULL,
    description             VARCHAR(100)  NOT NULL,
    created_at    TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    updated_at    TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    CONSTRAINT pk_user_rating_description PRIMARY KEY (id)
);

